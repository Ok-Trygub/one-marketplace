INSERT INTO orders (user_id, status, total, created_at)
SELECT
    floor(random() * (SELECT count(*) FROM users) + 1)::bigint,
    CASE
        WHEN random() < 0.80 THEN 'paid'
        WHEN random() < 0.75 THEN 'pending'
        ELSE 'cancelled'
        END,
    0,
    now() - random() * interval '730 days'
FROM generate_series(1, 200000) AS g;

INSERT INTO order_items (order_id, product_id, quantity, unit_price)
SELECT line.order_id, p.id, line.quantity, p.price
FROM (
         SELECT
             o.id AS order_id,
             floor(random() * (SELECT count(*) FROM products) + 1)::bigint AS product_id,
             floor(random() * 3 + 1)::int AS quantity
         FROM (
                  SELECT id, floor(random() * 3 + 1)::int AS items_count
                  FROM orders
              ) AS o
                  CROSS JOIN LATERAL generate_series(1, o.items_count) AS g
     ) AS line
         JOIN products AS p ON p.id = line.product_id;

UPDATE orders AS o
SET total = s.total
    FROM (
  SELECT order_id, sum(quantity * unit_price) AS total
  FROM order_items
  GROUP BY order_id
) AS s
WHERE s.order_id = o.id;

